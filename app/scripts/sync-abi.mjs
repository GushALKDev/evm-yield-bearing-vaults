// Regenerates src/abi/*.ts from the Foundry build output (run `forge build` at the repo root first).
// The ABIs are committed, so the app builds without Foundry, on Workers Builds too.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const out = join(here, '..', '..', 'out')
const target = join(here, '..', 'src', 'abi')

// [artifact file, contract, export name, keep only errors]
const contracts = [
  ['YieldBearingVault.sol', 'YieldBearingVault', 'vaultAbi', false],
  ['WETHLoopStrategy.sol', 'WETHLoopStrategy', 'strategyAbi', false],
  ['DemoOperator.sol', 'DemoOperator', 'operatorAbi', false],
  ['IAaveV3Testnet.sol', 'IAaveV3Testnet', 'aavePoolAbi', false],
  ['IAaveV3Testnet.sol', 'IAaveScaledBalanceToken', 'aaveTokenAbi', false],
  ['IAaveV3Testnet.sol', 'IAaveOracle', 'aaveOracleAbi', false],
  ['IWETH9.sol', 'IWETH9', 'wethAbi', false],
  // Errors a flash loan can raise inside the Uniswap V4 PoolManager
  ['IPoolManager.sol', 'IPoolManager', 'poolManagerErrorsAbi', true],
  ['CustomRevert.sol', 'CustomRevert', 'customRevertErrorsAbi', true],
  ['Currency.sol', 'CurrencyLibrary', 'currencyErrorsAbi', true],
]

mkdirSync(target, { recursive: true })
const index = []
for (const [file, name, exportName, errorsOnly] of contracts) {
  const artifact = JSON.parse(readFileSync(join(out, file, `${name}.json`), 'utf8'))
  const abi = errorsOnly ? artifact.abi.filter((item) => item.type === 'error') : artifact.abi
  const body =
    `// Generated by scripts/sync-abi.mjs from out/${file}/${name}.json. Do not edit.\n` +
    `export const ${exportName} = ${JSON.stringify(abi, null, 2)} as const\n`
  writeFileSync(join(target, `${name}.ts`), body)
  index.push(`export { ${exportName} } from './${name}'`)
  console.log(`${name}: ${abi.length} entries`)
}
writeFileSync(join(target, 'index.ts'), `// Generated by scripts/sync-abi.mjs. Do not edit.\n${index.join('\n')}\n`)
